import { createRequire } from 'node:module';
import { createApp } from '../server/src/app.js';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const OUT = new URL('./out/', import.meta.url).pathname;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const app = await createApp({ port: 0, host: '127.0.0.1', pgliteDir: 'memory://', databaseUrl: undefined as any, ambientNpcs: 10, crowdNpcs: 0, lingerSeconds: 1, logLevel: 'warn', threats: false });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2 });
page.on('pageerror', (e: Error) => console.log('pageerror', e.message));
const shot = async (n: string) => { await page.screenshot({ path: `${OUT}${n}.png`, timeout: 180000 }); console.log('📸', n); };
await page.goto(`http://127.0.0.1:${app.port}`);
await page.fill('#username', 'admintester'); await page.fill('#password', 'admintester');
await page.click('#btn-login'); await page.click('#btn-create'); await page.fill('#char-name', 'Nia Corvo'); await page.click('#btn-next');
for (let i = 0; i < 8; i++) await page.click('#btn-next').catch(() => {});
await page.click('#btn-create-final');
await page.waitForFunction(() => (window as any).__vt && (window as any).__vt.me().id > 0, null, { timeout: 120000 });
await sleep(4000);
await page.evaluate(() => document.querySelectorAll('.overlay').forEach((o) => o.remove()));
const c = [...app.world.conns.values()][0];
const w = app.world as any;
const p = c.p!, e = c.e!;
const W = w.combat.wounds;
const wp = (id: string) => ({ id, w: w.c.items.find((i: any) => i.id === id).weapon });
W.rng = () => 0.99;
W.hit(e, p, 'brazo_der', 14, wp('pistola-ligera'), true);
W.hit(e, p, 'pierna_izq', 30, wp('katana-termica'), true);
W.hit(e, p, 'torso', 4, wp('navaja'), true);
p.body.wounds.mano_izq = 40; W.rng = () => 0;
W.hit(e, p, 'mano_izq', 30, wp('katana-termica'), true);
W.rng = Math.random;
const amp = p.body.list.find((x: any) => x.kind === 'amputacion'); amp.bandaged = true; amp.bandageAge = 3;
const ras = p.body.list.find((x: any) => x.kind === 'rasguno'); ras.infection = 0.62;
p.hp = Math.round(p.hp * 0.55);
for (const it of ['venda', 'sutura', 'pinzas', 'antiseptico', 'antibioticos', 'estim']) await w.admin.give(p, it, 3);
W.tick0(p.body);
w.survival.sheet(c);
await sleep(2500);
for (let i = 0; i < 3; i++) await page.click('.overlay button.btn.primary', { timeout: 1500 }).catch(() => {});
await page.evaluate(() => document.querySelectorAll('.overlay').forEach((o) => o.remove()));
await page.keyboard.press('h'); await sleep(2500);
await shot('v18-01-salud');
const row = await page.$('.hp-wound');
if (row) { await row.click({ button: 'right' }); await sleep(800); await shot('v18-02-menu-tratamiento'); }
await page.keyboard.press('Escape'); await sleep(400);
await page.evaluate(() => document.querySelectorAll('.panel, .bp-pop').forEach((o) => o.remove()));
await page.keyboard.press('i'); await sleep(4500);
await shot('v18-03-mochila-admin');
await browser.close(); await app.close(); process.exit(0);
